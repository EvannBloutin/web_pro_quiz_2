#!/usr/bin/env python3
"""Generates the JavaBean model classes (getters/setters) used by the JSP/EL views."""
import os
OUT = os.path.join(os.path.dirname(__file__), "..", "src/main/java/com/campuslibrary/model")
SPEC = {
 "User": ([("long","id"),("String","name"),("String","email"),("String","passwordHash"),("boolean","admin"),
           ("LocalDateTime","createdAt"),("int","activeLoans")],
  """    public String getInitials() {
        String[] p = name.trim().split("\\\\s+");
        String s = p[0].substring(0, 1) + (p.length > 1 ? p[p.length - 1].substring(0, 1) : "");
        return s.toUpperCase();
    }
    public String getFirstName() { return name.trim().split("\\\\s+")[0]; }
    public String getRole() { return admin ? "Librarian" : "Member"; }"""),
 "Category": ([("long","id"),("String","name"),("String","description"),("String","color"),("int","bookCount")], ""),
 "Book": ([("long","id"),("long","categoryId"),("String","title"),("String","author"),("String","isbn"),("String","description"),
           ("Integer","publishedYear"),("String","coverUrl"),("int","copiesTotal"),("int","copiesAvailable"),
           ("LocalDateTime","createdAt"),("String","categoryName"),("String","categoryColor"),("double","avgRating"),
           ("int","reviewCount"),("int","loanCount"),("boolean","favorite")],
  """    public boolean isAvailable() { return copiesAvailable > 0; }
    public int getPattern() { return (int) (id % 4); }
    public String getAvgRatingText() { return String.format(java.util.Locale.ROOT, "%.1f", avgRating); }"""),
 "Loan": ([("long","id"),("long","userId"),("long","bookId"),("LocalDate","borrowedAt"),("LocalDate","dueAt"),
           ("LocalDate","returnedAt"),("int","renewals"),("String","bookTitle"),("String","bookAuthor"),("String","bookIsbn"),
           ("String","bookCoverUrl"),("long","bookCategoryId"),("String","categoryColor"),("String","userName")],
  """    public static final int FINE_PER_DAY = 1000;
    public boolean isActive() { return returnedAt == null; }
    public boolean isOverdue() { return returnedAt == null && dueAt.isBefore(LocalDate.now()); }
    public int getOverdueDays() {
        LocalDate end = returnedAt != null ? returnedAt : LocalDate.now();
        long d = java.time.temporal.ChronoUnit.DAYS.between(dueAt, end);
        return (int) Math.max(0, d);
    }
    public int getDaysLeft() { return (int) java.time.temporal.ChronoUnit.DAYS.between(LocalDate.now(), dueAt); }
    public boolean isDueSoon() { return returnedAt == null && !isOverdue() && getDaysLeft() <= 3; }
    public long getFine() { return (long) getOverdueDays() * FINE_PER_DAY; }
    public String getStatus() { return returnedAt != null ? "RETURNED" : (isOverdue() ? "OVERDUE" : "ACTIVE"); }
    public boolean isCanRenew() { return returnedAt == null && !isOverdue() && renewals < 2; }"""),
 "Review": ([("long","id"),("long","userId"),("long","bookId"),("int","rating"),("String","comment"),
             ("LocalDateTime","createdAt"),("String","userName")], ""),
 "Reservation": ([("long","id"),("long","userId"),("long","bookId"),("String","status"),("LocalDateTime","createdAt"),
                  ("String","bookTitle"),("String","bookAuthor"),("String","bookIsbn"),("String","bookCoverUrl"),("long","bookCategoryId"),
                  ("String","categoryColor"),("String","userName"),("int","position"),("int","copiesAvailable")],
  """    public boolean isReady() { return "READY".equals(status); }
    public boolean isOpen() { return "WAITING".equals(status) || "READY".equals(status); }"""),
 "Announcement": ([("long","id"),("long","authorId"),("String","title"),("String","body"),("boolean","pinned"),
                   ("LocalDateTime","createdAt"),("String","authorName")], ""),
}
def cap(s): return s[0].upper() + s[1:]
for name, (fields, extra) in SPEC.items():
    imports = set()
    for t, _ in fields:
        if t.startswith("Local"): imports.add("java.time." + t)
    out = ["package com.campuslibrary.model;", ""]
    out += ["import %s;" % i for i in sorted(imports)]
    if imports: out.append("")
    out.append("/** Model (generated by scripts/gen_models.py). Plain JavaBean so it can be read from JSP/EL. */")
    out.append("public class %s {" % name)
    for t, n in fields: out.append("    private %s %s;" % (t, n))
    out.append("")
    for t, n in fields:
        g = ("is" if t == "boolean" else "get") + cap(n)
        out.append("    public %s %s() { return %s; }" % (t, g, n))
        out.append("    public void set%s(%s v) { this.%s = v; }" % (cap(n), t, n))
    if extra: out += ["", extra]
    out.append("}")
    open(os.path.join(OUT, name + ".java"), "w").write("\n".join(out) + "\n")
print("generated", len(SPEC), "models")
